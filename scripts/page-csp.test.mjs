#!/usr/bin/env node
// Static gate for the Content-Security-Policy <meta> on every content page.
// GitHub Pages cannot send response headers, so the policy ships as a <meta>
// tag and inline scripts are allow-listed by sha256 hash. A hash that drifts
// from its script body silently disables that script in every browser, so this
// test recomputes every hash from the committed HTML and fails on mismatch
// (scripts/update-csp-hashes.mjs rewrites the policy; the helpers live in
// scripts/page-csp.mjs).
// It also keeps the policy from regressing to 'unsafe-inline'/'unsafe-eval',
// keeps every external <img> origin covered by img-src and every external
// <iframe> origin covered by frame-src (with no frame-src origin left unused).
// Zero dependencies. Usage: node --test scripts/page-csp.test.mjs
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { relative } from "node:path";
import { ROOT, htmlFiles, isRedirectPage } from "./html-pages.mjs";
import { REGEN_HINT, externalFrameOrigins, externalImageOrigins, inlineScriptSources, parseCsp, problemsOf, sha256Source } from "./page-csp.mjs";

// --- per-page gates ---------------------------------------------------------

for (const file of htmlFiles()) {
  const rel = relative(ROOT, file);
  const html = readFileSync(file, "utf8");
  // Shortcut redirect pages are generated by make-redirects.sh and carry only a
  // meta refresh; they load no scripts and are out of scope.
  if (isRedirectPage(html)) continue;

  test(`${rel}: CSP meta present, hashes match inline scripts, no unsafe-inline`, () => {
    assert.deepEqual(problemsOf(html), []);
  });
}

// --- fixture self-tests -----------------------------------------------------

function fixture({ csp, script = "console.log(1)", handler = "", img = "", frame = "" } = {}) {
  const meta = csp === null ? "" : `<meta http-equiv="Content-Security-Policy" content="${csp}">`;
  return `<!doctype html><html><head><meta charset="utf-8">${meta}<title>x</title></head><body>${img}${frame}<p${handler ? ` onerror="${handler}"` : ""}></p><script type="application/ld+json">{"@context":"https://schema.org","@type":"Thing"}</script><script>${script}</script></body></html>`;
}

const BASE = "default-src 'none'; img-src 'self'; base-uri 'none'; form-action 'none'";

test("fixture: correct policy passes", () => {
  const h = sha256Source("console.log(1)");
  assert.deepEqual(problemsOf(fixture({ csp: `${BASE}; script-src ${h}` })), []);
});

test("fixture: missing meta is reported", () => {
  assert.deepEqual(problemsOf(fixture({ csp: null })), ['missing <meta http-equiv="Content-Security-Policy">']);
});

test("fixture: duplicate CSP metas are reported", () => {
  const csp = `${BASE}; script-src ${sha256Source("console.log(1)")}`;
  const html = fixture({ csp }).replace("</head>", `<meta http-equiv="Content-Security-Policy" content="${csp}"></head>`);
  assert.deepEqual(problemsOf(html), ["expected exactly one CSP meta, found 2"]);
});

test("fixture: missing script-src is reported", () => {
  assert.deepEqual(problemsOf(fixture({ csp: BASE })), ["script-src directive missing"]);
});

for (const bad of ["*", "http:", "https:", "data:"]) {
  test(`fixture: script-src rejects ${bad}`, () => {
    const h = sha256Source("console.log(1)");
    assert.deepEqual(problemsOf(fixture({ csp: `${BASE}; script-src ${h} ${bad}` })), [`script-src must not contain ${bad}`]);
  });
}

test("fixture: unused 'unsafe-hashes' is reported", () => {
  const h = sha256Source("console.log(1)");
  assert.deepEqual(problemsOf(fixture({ csp: `${BASE}; script-src ${h} 'unsafe-hashes'` })), ["'unsafe-hashes' present but no inline event handlers remain"]);
});

for (const baseUri of ["", "; base-uri https://example.org"]) {
  test(`fixture: missing or invalid base-uri is reported (${baseUri || "missing"})`, () => {
    const h = sha256Source("console.log(1)");
    const csp = `default-src 'none'; img-src 'self'; form-action 'none'; script-src ${h}${baseUri}`;
    assert.deepEqual(problemsOf(fixture({ csp })), ["base-uri must be 'none' or 'self'"]);
  });
}

test("fixture: base-uri 'self' is accepted", () => {
  const h = sha256Source("console.log(1)");
  assert.deepEqual(problemsOf(fixture({ csp: `${BASE.replace("base-uri 'none'", "base-uri 'self'")}; script-src ${h}` })), []);
});

test("fixture: missing form-action is reported", () => {
  const h = sha256Source("console.log(1)");
  assert.deepEqual(problemsOf(fixture({ csp: `default-src 'none'; img-src 'self'; base-uri 'none'; script-src ${h}` })), ["form-action directive missing"]);
});

test("fixture: img-src accepts the https: scheme and overrides default-src", () => {
  const h = sha256Source("console.log(1)");
  const img = '<img src="https://github.com/octocat.png" alt="">';
  assert.deepEqual(problemsOf(fixture({ csp: `${BASE.replace("img-src 'self'", "img-src https:")}; script-src ${h}`, img })), []);
  assert.deepEqual(problemsOf(fixture({ csp: `${BASE.replace("img-src 'self'; ", "")}; script-src ${h}`, img })), ["img-src does not allow external <img> origin https://github.com"]);
  // A permissive fallback lets the image through, but still violates the
  // independent default-src 'none' rule.
  assert.deepEqual(problemsOf(fixture({ csp: `default-src https:; base-uri 'none'; form-action 'none'; script-src ${h}`, img })), ["default-src must be 'none' so every fetch type is allow-listed explicitly"]);
});

test("fixture: drifted script body is reported with both the missing and the stale hash", () => {
  const stale = sha256Source("console.log(0)");
  const want = sha256Source("console.log(1)");
  const problems = problemsOf(fixture({ csp: `${BASE}; script-src ${stale}` }));
  assert.deepEqual(problems, [
    `script-src lacks ${want} for an inline script or event handler (body edited without updating the policy? ${REGEN_HINT})`,
    `script-src has stale hash ${stale} that matches no inline script or handler (${REGEN_HINT})`,
  ]);
});

test("fixture: JSON-LD blocks are not hashed", () => {
  const h = sha256Source("console.log(1)");
  assert.equal(inlineScriptSources(fixture({ csp: `${BASE}; script-src ${h}` })).length, 1);
});

test("fixture: 'unsafe-inline' and 'unsafe-eval' in script-src are rejected", () => {
  const h = sha256Source("console.log(1)");
  const problems = problemsOf(fixture({ csp: `${BASE}; script-src 'unsafe-inline' 'unsafe-eval' ${h}` }));
  assert.deepEqual(problems, ["script-src must not contain 'unsafe-inline'", "script-src must not contain 'unsafe-eval'"]);
});

test("fixture: a page without <head> has no policy", () => {
  assert.equal(parseCsp("<html><body><p>x</p></body></html>"), null);
  assert.deepEqual(problemsOf("<html><body><p>x</p></body></html>"), ['missing <meta http-equiv="Content-Security-Policy">']);
});

test("fixture: a CSP meta without a content attribute parses to no directives and a null content offset", () => {
  const html = fixture({ csp: null }).replace("<title>", '<meta http-equiv="Content-Security-Policy"><title>');
  const csp = parseCsp(html);
  assert.deepEqual(csp.directives, {});
  assert.equal(csp.count, 1);
  assert.equal(csp.content, null);
  assert.equal(csp.contentAt, -1);
  assert.equal(csp.contentQuote, null);
  assert.deepEqual(problemsOf(html), [
    "script-src directive missing",
    "base-uri must be 'none' or 'self'",
    "form-action directive missing",
  ]);
});

test("fixture: empty directive segments (`;;`, trailing `;`) are ignored", () => {
  const h = sha256Source("console.log(1)");
  const html = fixture({ csp: `${BASE};; script-src ${h};` });
  assert.deepEqual(Object.keys(parseCsp(html).directives), ["default-src", "img-src", "base-uri", "form-action", "script-src"]);
  assert.deepEqual(problemsOf(html), []);
});

test("fixture: script-src present but default-src missing is reported", () => {
  const h = sha256Source("console.log(1)");
  assert.deepEqual(problemsOf(fixture({ csp: `img-src 'self'; base-uri 'none'; form-action 'none'; script-src ${h}` })), [
    "default-src must be 'none' so every fetch type is allow-listed explicitly",
  ]);
});

test("fixture: with neither img-src nor default-src, an external <img> origin is not allowed", () => {
  const h = sha256Source("console.log(1)");
  const img = '<img src="https://github.com/octocat.png" alt="">';
  assert.deepEqual(problemsOf(fixture({ csp: `base-uri 'none'; form-action 'none'; script-src ${h}`, img })), [
    "default-src must be 'none' so every fetch type is allow-listed explicitly",
    "img-src does not allow external <img> origin https://github.com",
  ]);
});

test("fixture: <img> without src and relative src contribute no external origin", () => {
  assert.deepEqual(externalImageOrigins('<img alt=""><img src="/og.png" alt=""><IMG SRC="HTTPS://Example.org/a.png">'), ["https://example.org"]);
  const h = sha256Source("console.log(1)");
  assert.deepEqual(problemsOf(fixture({ csp: `${BASE}; script-src ${h}`, img: '<img alt="">' })), []);
});

test("fixture: inline event handler requires 'unsafe-hashes' plus its hash", () => {
  const h = sha256Source("console.log(1)");
  const hh = sha256Source("this.hidden=true");
  assert.deepEqual(problemsOf(fixture({ csp: `${BASE}; script-src ${h} 'unsafe-hashes' ${hh}`, handler: "this.hidden=true" })), []);
  const problems = problemsOf(fixture({ csp: `${BASE}; script-src ${h}`, handler: "this.hidden=true" }));
  assert.deepEqual(problems, [
    `script-src lacks ${hh} for an inline script or event handler (body edited without updating the policy? ${REGEN_HINT})`,
    "inline event handlers present but script-src lacks 'unsafe-hashes'",
  ]);
});

test("fixture: external <img> origin must be in img-src", () => {
  const h = sha256Source("console.log(1)");
  const img = '<img src="https://github.com/octocat.png" alt="">';
  assert.deepEqual(problemsOf(fixture({ csp: `${BASE}; script-src ${h}`, img })), ["img-src does not allow external <img> origin https://github.com"]);
  assert.deepEqual(problemsOf(fixture({ csp: `default-src 'none'; img-src 'self' https://github.com; base-uri 'none'; form-action 'none'; script-src ${h}`, img })), []);
});

const FRAME = '<iframe src="https://www.youtube-nocookie.com/embed/x" title="x"></iframe>';

test("fixture: <iframe> without src, relative src and srcdoc contribute no external origin", () => {
  assert.deepEqual(externalFrameOrigins('<iframe title="a"></iframe><iframe src="/embed.html" title="b"></iframe><iframe srcdoc="<p>x</p>" title="c"></iframe><IFRAME SRC="HTTPS://Example.org/e?x=1" title="d"></IFRAME>'), ["https://example.org"]);
  const h = sha256Source("console.log(1)");
  assert.deepEqual(problemsOf(fixture({ csp: `${BASE}; script-src ${h}`, frame: '<iframe src="/embed.html" title="x"></iframe>' })), []);
});

test("fixture: external <iframe> origin must be in frame-src", () => {
  const h = sha256Source("console.log(1)");
  assert.deepEqual(problemsOf(fixture({ csp: `${BASE}; frame-src https://example.org; script-src ${h}`, frame: FRAME })), [
    "frame-src does not allow external <iframe> origin https://www.youtube-nocookie.com",
    "frame-src allows https://example.org but no <iframe> on the page uses it",
  ]);
  assert.deepEqual(problemsOf(fixture({ csp: `${BASE}; frame-src https://www.youtube-nocookie.com; script-src ${h}`, frame: FRAME })), []);
  assert.deepEqual(problemsOf(fixture({ csp: `${BASE}; frame-src https:; script-src ${h}`, frame: FRAME })), []);
});

test("fixture: without frame-src, child-src then default-src governs <iframe> origins", () => {
  const h = sha256Source("console.log(1)");
  assert.deepEqual(problemsOf(fixture({ csp: `${BASE}; child-src https://www.youtube-nocookie.com; script-src ${h}`, frame: FRAME })), []);
  assert.deepEqual(problemsOf(fixture({ csp: `${BASE}; script-src ${h}`, frame: FRAME })), [
    "frame-src does not allow external <iframe> origin https://www.youtube-nocookie.com",
  ]);
  assert.deepEqual(problemsOf(fixture({ csp: `img-src 'self'; base-uri 'none'; form-action 'none'; script-src ${h}`, frame: FRAME })), [
    "default-src must be 'none' so every fetch type is allow-listed explicitly",
    "frame-src does not allow external <iframe> origin https://www.youtube-nocookie.com",
  ]);
});

test("fixture: a frame-src origin no <iframe> uses is reported; 'self' and 'none' are not origins", () => {
  const h = sha256Source("console.log(1)");
  assert.deepEqual(problemsOf(fixture({ csp: `${BASE}; frame-src 'self' https://www.youtube-nocookie.com; script-src ${h}` })), [
    "frame-src allows https://www.youtube-nocookie.com but no <iframe> on the page uses it",
  ]);
  assert.deepEqual(problemsOf(fixture({ csp: `${BASE}; frame-src 'none'; script-src ${h}` })), []);
});

test("fixture: policy placed after a <script> in <head> is reported", () => {
  const h = sha256Source("console.log(1)");
  const html = `<!doctype html><html><head><meta charset="utf-8"><script>console.log(1)</script><meta http-equiv="Content-Security-Policy" content="${BASE}; script-src ${h}"></head><body></body></html>`;
  assert.deepEqual(problemsOf(html), ["CSP meta must precede every <script>/<link>/<img>/<style> in <head> (a meta policy only governs what follows it)"]);
});

test("fixture: default-src other than 'none' is reported", () => {
  const h = sha256Source("console.log(1)");
  const problems = problemsOf(fixture({ csp: `default-src 'self'; img-src 'self'; base-uri 'none'; form-action 'none'; script-src ${h}` }));
  assert.deepEqual(problems, ["default-src must be 'none' so every fetch type is allow-listed explicitly"]);
});
